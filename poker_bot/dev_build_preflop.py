"""
Dev tool, not submitted: writes preflop_tables.py.

    .venv/bin/python dev_build_preflop.py [samples_per_pair]

EQ[a * 169 + b] is class a's share of the pot against class b (x 10000),
by Monte Carlo over non-overlapping combo pairs and random boards. HS[a]
is class a's share against a random hand (x 10000), weighted by how many
combo pairs each class matchup has.
"""

import multiprocessing
import random
import sys
import time

from handeval import Evaluator, class_name

EV = None


def _init():
    global EV
    EV = Evaluator()


def _row(args):
    a, samples, seed = args
    ev = EV
    rng = random.Random(seed)
    by_class = [[] for _ in range(169)]
    for x, y in ev.combos:
        by_class[ev.cls[ev.combo_index[(x, y)]]].append((x, y))
    deck = list(range(52))
    out = []
    for b in range(a, 169):
        pairs = [
            (p, q) for p in by_class[a] for q in by_class[b]
            if len({p[0], p[1], q[0], q[1]}) == 4
        ]
        if a == b:
            out.append((b, 0.5, len(pairs)))
            continue
        won = 0.0
        for _ in range(samples):
            p, q = pairs[rng.randrange(len(pairs))]
            used = (p[0], p[1], q[0], q[1])
            board = [c for c in rng.sample(deck, 9) if c not in used][:5]
            va = ev.value([p[0], p[1]] + board)
            vb = ev.value([q[0], q[1]] + board)
            if va > vb:
                won += 1.0
            elif va == vb:
                won += 0.5
        out.append((b, won / samples, len(pairs)))
    return a, out


def main():
    samples = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
    start = time.time()
    eq = [[0.5] * 169 for _ in range(169)]
    count = [[0] * 169 for _ in range(169)]
    jobs = [(a, samples, 1000 + a) for a in range(169)]
    with multiprocessing.Pool(initializer=_init) as pool:
        for a, out in pool.imap_unordered(_row, jobs):
            for b, e, n in out:
                eq[a][b] = e
                eq[b][a] = 1.0 - e
                count[a][b] = count[b][a] = n
    hs = []
    for a in range(169):
        total = sum(count[a])
        hs.append(sum(eq[a][b] * count[a][b] for b in range(169)) / total)
    with open("preflop_tables.py", "w") as file:
        file.write(
            '"""Generated by dev_build_preflop.py: do not edit.\n\n'
            "EQ[a * 169 + b]: class a's share of the pot against class b, "
            "x 10000.\nHS[a]: class a's share against a random hand, "
            'x 10000.\n"""\n\n'
        )
        flat = [int(round(eq[a][b] * 10000)) for a in range(169)
                for b in range(169)]
        file.write("EQ = [\n")
        for i in range(0, len(flat), 24):
            file.write("    " + ", ".join(map(str, flat[i:i + 24])) + ",\n")
        file.write("]\n\nHS = [\n")
        hs_int = [int(round(h * 10000)) for h in hs]
        for i in range(0, 169, 13):
            file.write("    " + ", ".join(map(str, hs_int[i:i + 13])) + ",\n")
        file.write("]\n")
    best = sorted(range(169), key=lambda a: -hs[a])
    print("top:", [(class_name(a), round(hs[a], 3)) for a in best[:8]])
    print("bottom:", [(class_name(a), round(hs[a], 3)) for a in best[-5:]])
    aa, kk = 12 * 13 + 12, 11 * 13 + 11
    print("AA vs KK", round(eq[aa][kk], 3), "secs", round(time.time() - start))


if __name__ == "__main__":
    main()
